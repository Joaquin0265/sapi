-- ---------------------------------------------------------------- SECUENCIAS
CREATE SEQUENCE SEQ_SEG_ROL START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_SEG_PERSONAL START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;
CREATE SEQUENCE SEQ_SEG_USUARIO START WITH 1 INCREMENT BY 1 NOCACHE NOCYCLE;

-- ---------------------------------------------------------------- TABLA ROL
CREATE TABLE SEG_ROL (
    ID_ROL NUMBER(19) NOT NULL,
    NOMBRE VARCHAR2(50) NOT NULL,
    CONSTRAINT PK_SEG_ROL PRIMARY KEY (ID_ROL),
    CONSTRAINT UK_SEG_ROL_NOMBRE UNIQUE (NOMBRE)
);

-- ---------------------------------------------------------------- TABLA PERSONAL
CREATE TABLE SEG_PERSONAL (
    ID_PERSONAL NUMBER(19) NOT NULL,
    DNI CHAR(8) NOT NULL,
    NOMBRES VARCHAR2(100) NOT NULL,
    APELLIDOS VARCHAR2(100) NOT NULL,
    CORREO VARCHAR2(100),
    ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_SEG_PERSONAL PRIMARY KEY (ID_PERSONAL),
    CONSTRAINT UK_SEG_PERSONAL_DNI UNIQUE (DNI),
    CONSTRAINT CK_SEG_PERSONAL_ACTIVO CHECK (ACTIVO IN (0, 1))
);

-- ---------------------------------------------------------------- TABLA USUARIO
CREATE TABLE SEG_USUARIO (
    ID_USUARIO NUMBER(19) NOT NULL,
    ID_PERSONAL NUMBER(19) NOT NULL,
    ID_ROL NUMBER(19) NOT NULL,
    NOMBRE_USUARIO VARCHAR2(50) NOT NULL,
    CLAVE_ENCRIPTADA VARCHAR2(255) NOT NULL,
    ACTIVO NUMBER(1) DEFAULT 1 NOT NULL,
    CONSTRAINT PK_SEG_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_SEG_USUARIO_USERNAME UNIQUE (NOMBRE_USUARIO),
    CONSTRAINT FK_SEG_USU_PERSONAL FOREIGN KEY (ID_PERSONAL) REFERENCES SEG_PERSONAL(ID_PERSONAL),
    CONSTRAINT FK_SEG_USU_ROL FOREIGN KEY (ID_ROL) REFERENCES SEG_ROL(ID_ROL),
    CONSTRAINT CK_SEG_USUARIO_ACTIVO CHECK (ACTIVO IN (0, 1))
);

